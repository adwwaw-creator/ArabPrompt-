/**
 * Applies a selected story path choice to a MovieProject, updating affected scenes,
 * dialogue, action beats, camera motions, and AI video prompts.
 */
export function applyStoryPathToMovieProject(project: MovieProject, pathId: string): MovieProject {
  if (!project.availablePaths || project.availablePaths.length === 0) return project;
  const path = project.availablePaths.find(p => p.id === pathId);
  if (!path) return project;

  // Find original legend template to get base scene definitions
  const originalLegend = ARABIC_HISTORICAL_LEGENDS.find(l => l.id === project.id);
  const baseScenes = originalLegend 
    ? originalLegend.readyScenes.map((sc, i) => ({ ...sc, durationSeconds: 10, sceneNumber: i + 1 }))
    : project.scenes;

  const updatedScenes = baseScenes.map(scene => {
    const override = path.sceneOverrides.find(o => o.sceneNumber === scene.sceneNumber);
    if (!override) return { ...scene };

    return {
      ...scene,
      titleAr: override.titleAr ?? scene.titleAr,
      titleEn: override.titleEn ?? scene.titleEn,
      dramaticActionAr: override.dramaticActionAr ?? scene.dramaticActionAr,
      screenplayBeatAr: override.screenplayBeatAr ?? scene.screenplayBeatAr,
      screenplayBeatEn: override.screenplayBeatEn ?? scene.screenplayBeatEn,
      dialogueAr: override.dialogueAr ?? scene.dialogueAr,
      dialogueEn: override.dialogueEn ?? scene.dialogueEn,
      dialogueSpeaker: override.dialogueSpeaker ?? scene.dialogueSpeaker,
      dialogueEmotion: override.dialogueEmotion ?? scene.dialogueEmotion,
      dialogueTiming: override.dialogueTiming ?? scene.dialogueTiming,
      videoPromptEn: override.videoPromptEn ?? scene.videoPromptEn,
      soundDesign: override.soundDesign ?? scene.soundDesign,
      cameraMotion: override.cameraMotion ?? scene.cameraMotion,
      shotType: override.shotType ?? scene.shotType,
    };
  });

  return {
    ...project,
    scenes: updatedScenes,
    activePathId: pathId,
    updatedAt: new Date().toISOString()
  };
}

/**
 * Converts a HistoricalLegendScreenplay directly into a 100% compliant MovieProject object
 * conforming to CinemaMovieStudio's internal movies data model, with initial path applied.
 */
export function convertLegendToMovieProject(legend: HistoricalLegendScreenplay): MovieProject {
  const initialPathId = legend.defaultPathId || (legend.availablePaths && legend.availablePaths[0]?.id);
  const baseProject: MovieProject = {
    id: legend.id,
    titleAr: legend.titleAr,
    titleEn: legend.titleEn,
    concept: legend.conceptAr,
    genre: legend.genreAr,
    visualStyle: legend.recommendedStyleEn,
    targetAiModel: 'Runway Gen-3 Alpha',
    loglineAr: legend.taglineAr,
    loglineEn: legend.taglineEn,
    storySynopsisAr: legend.conceptAr,
    storySynopsisEn: legend.conceptEn,
    characterAnchor: {
      name: legend.hero.name,
      role: legend.hero.roleAr,
      gender: legend.hero.gender,
      age: legend.hero.age,
      faceDescriptionAr: legend.hero.featuresAr,
      faceDescriptionEn: legend.hero.featuresEn,
      consistencyPromptToken: `[Consistent Face Anchor: ${legend.hero.name.split(' ')[0]}, ${legend.hero.age}yo, ${legend.hero.featuresEn}, identical facial bone structure across all camera angles]`
    },
    scenes: legend.readyScenes.map((sc, i) => ({
      ...sc,
      durationSeconds: 10,
      sceneNumber: i + 1
    })),
    totalDurationSeconds: legend.readyScenes.length * 10,
    actStructure: legend.acts,
    availablePaths: legend.availablePaths,
    activePathId: initialPathId,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };

  if (initialPathId && legend.availablePaths) {
    return applyStoryPathToMovieProject(baseProject, initialPathId);
  }
  return baseProject;
}

